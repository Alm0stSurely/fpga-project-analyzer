"""Markdown design document; diagram images come from the viewer's own SVG export (headless Chrome)."""
from __future__ import annotations

import html
import os
import re
import shutil
import subprocess

from . import model as M, summary as S, viewer as V

SEV = {"high": "High", "med": "Medium", "low": "Low", "info": "Info"}


def find_chrome():
    for c in ("google-chrome-stable", "google-chrome", "chromium", "chromium-browser", "chrome", "msedge",
              "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
              "C:/Program Files/Google/Chrome/Application/chrome.exe"):
        w = shutil.which(c) or (c if os.path.isfile(c) else None)
        if w:
            return w
    return None


def capture(chrome, html_path, level, timeout=90):
    """One diagram level as standalone SVG, exported by the viewer itself."""
    url = "file://" + os.path.abspath(html_path) + "?export=svg#" + (level or "/")
    args = [chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--window-size=1600,1000",
            "--virtual-time-budget=10000", "--dump-dom", url]
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        args.insert(1, "--no-sandbox")  # Chrome refuses to sandbox as root (containers)
    try:
        p = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        return None
    m = re.search(r'<textarea id="fpa-export"[^>]*>(.*?)</textarea>', p.stdout, re.S)
    return html.unescape(m.group(1)) if m and m.group(1).strip() else None


def _cell(x):
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(head, rows):
    if not rows:
        return []
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out + [""]


def _levels(design, limit):
    """Top level, then openable blocks (those with findings first), up to limit."""
    defs = design["defs"]
    found = {}
    for f in design.get("findings", []):
        parts = [p for p in f["path"].split("/") if p]
        for k in range(1, len(parts)):
            found["/" + "/".join(parts[:k])] = found.get("/" + "/".join(parts[:k]), 0) + 1
    cands = []
    for path, d, inst in M.walk(design, 3):
        body = M.body(design, d)
        real = [i for i in body["insts"] if defs[i["def"]]["kind"] not in ("reg", "comb", "latch", "prim")]
        if real or (body["insts"] and found.get(path)):
            cands.append((-found.get(path, 0), path.count("/"), path))
    cands.sort()
    return [""] + [p for _, _, p in cands[:max(0, limit - 1)]]


def write(design, root, overlay=None, images=True, levels=6, log=print):
    overlay = overlay or {}
    out_dir = os.path.join(root, ".fpa")
    html_path = V.render(design, os.path.join(out_dir, "design.html"), overlay)
    d = V.merge_overlay(design, overlay)
    defs, meta = d["defs"], d["meta"]
    top = defs[d["top"]]
    notes = d.get("notes", {})
    img_dir = os.path.join(out_dir, "doc")
    os.makedirs(img_dir, exist_ok=True)
    shots = {}
    chrome = find_chrome() if images else None
    if images and not chrome:
        log("no Chrome/Chromium found: writing the document without diagram images")
    for lvl in (_levels(d, levels) if chrome else []):
        svg = capture(chrome, html_path, lvl)
        if svg:
            name = (lvl.strip("/").replace("/", "-") or "top") + ".svg"
            with open(os.path.join(img_dir, name), "w", encoding="utf-8") as f:
                f.write(svg)
            shots[lvl] = "doc/" + name
    md = ["# %s" % top["name"], ""]
    md.append(" · ".join(x for x in (meta.get("part"), "Vivado %s" % meta["tool"] if meta.get("tool") else None,
                                      "generated by FPGA Project Analyzer") if x))
    md.append("")
    if "" in shots:
        md += ["![%s block design](%s)" % (top["name"], shots[""]), ""]
    md += ["Interactive version: `design.html` (open in a browser, click blocks to go inside).", ""]
    bd_path, body = S._bd(d)
    addr = {}
    for a in (body or {}).get("addr", []):
        if not a.get("excluded") and "DDR" not in (a.get("block") or "").upper():
            addr.setdefault(a["slave"], []).append("%s %s" % (a["base"], a.get("range") or ""))
    level = M.body(d, top)
    rows = []
    for inst in level["insts"]:
        cd = defs[inst["def"]]
        if cd["kind"] in ("reg", "comb", "latch"):
            continue
        p = "/" + inst["name"]
        nf = sum(1 for f in d.get("findings", []) if f["path"] == p or f["path"].startswith(p + "/"))
        rows.append(["`%s`" % inst["name"], cd["name"], notes.get(p, ""), ", ".join(addr.get(bd_path + p, addr.get(p, []))),
                     nf or ""])
    md += ["## Blocks", ""] + _table(["Block", "Type", "Role", "Address", "Findings"], rows)
    doms = d.get("domains", {})
    if doms:
        cnt = {}
        for v in d.get("netdom", {}).values():
            for x in v:
                cnt[x] = cnt.get(x, 0) + 1
        md += ["## Clock domains", ""] + _table(["Domain", "Frequency", "Source", "Nets"], [
            [v["name"], "%g MHz" % (v["freq"] / 1e6) if v.get("freq") else "", "`%s`" % v["src"], cnt.get(k, 0)]
            for k, v in sorted(doms.items(), key=lambda kv: -cnt.get(kv[0], 0))[:16]])
    if body is not None and body.get("addr"):
        md += ["## Address map", ""] + _table(["Master", "Slave", "Interface", "Base", "Range"], [
            ["%s (%s)" % (a["master"], a["space"]) if a.get("space") else a["master"], a["slave"], a["intf"], a["base"],
             a.get("range") or a.get("high") or ""]
            for a in body["addr"] if not a.get("excluded")])
    if body is not None:
        irq = S._irq_map(d, bd_path, body)
        if irq:
            md += ["## Interrupts", ""] + ["- " + x for x in irq] + [""]
    ports = [[p["name"], p["dir"], p.get("bus") if p["kind"] == "bus" else p["kind"], p.get("w") or ""]
             for p in top["pins"]]
    md += ["## Top-level ports", ""] + _table(["Port", "Direction", "Kind", "Width"], ports)
    ann = d.get("annotations", [])
    if ann:
        by = {}
        for a in ann:
            by.setdefault(a["file"], set()).add(a["path"])
        md += ["## Software", ""] + _table(["File", "Uses"], [[f, ", ".join(sorted(p.strip("/") for p in ps))]
                                                               for f, ps in by.items()])
    fs = sorted(d.get("findings", []), key=lambda f: S.SEV_ORDER.get(f["sev"], 9))
    if fs:
        md += ["## Findings", ""] + _table(["Severity", "Where", "Finding", "Fix"], [
            [SEV.get(f["sev"], f["sev"]), "`%s`" % f["path"], f["title"] + (" - " + f["detail"] if f.get("detail") else ""),
             f.get("fix", "")] for f in fs])
    for lvl, img in shots.items():
        if not lvl:
            continue
        cd, _ = M.resolve(d, lvl)
        md += ["## Inside `%s`" % lvl, ""]
        if notes.get(lvl):
            md += [notes[lvl], ""]
        md += ["![%s](%s)" % (lvl, img), ""]
    out = os.path.join(out_dir, "design.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(md).rstrip() + "\n")
    return out, len(shots)
